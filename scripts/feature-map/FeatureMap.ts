/**
 * 声明式功能地图（Feature Map）：将全部公开 RPC v4 方法与桌面路由映射到可独立验证的功能域。
 */

/** 支持的驱动执行层。 */
export type DriverMode = 'agent' | 'desktop'

/** 单个功能的可执行验证场景描述。 */
export interface FeatureScenario {
  readonly id: string
  readonly mode: DriverMode
  readonly description: string
  readonly command?: string
}

/** 声明式功能条目，将 RPC 契约、Renderer 路由与双层验证场景绑定到同一功能 ID。 */
export interface FeatureEntry {
  readonly id: string
  readonly title: string
  readonly rpcMethods: readonly string[]
  readonly routes: readonly string[]
  readonly scenarios: readonly FeatureScenario[]
}

/** 显式豁免条目，要求附带不可省略的豁免理由。 */
export interface FeatureExemption {
  readonly target: string
  readonly reason: string
}

